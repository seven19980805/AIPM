async function handleAttachmentSelected(event: Event) {
  const input = event.target as HTMLInputElement
  const file = input.files?.[0]
  input.value = ''
  if (!file) {
    draftAttachmentDepartment.value = null
    draftAttachmentAutoGenerateDocuments.value = false
    return
  }

  uploadingAttachment.value = true
  globalError.value = ''
  try {
    const formData = new FormData()
    formData.append('file', file, file.name)
    formData.append('language', currentLanguage.value)
    const response = await fetch(apiUrl('/api/attachments/analyze'), {
      method: 'POST',
      body: formData,
    })
    const data = await response.json().catch(() => ({}))
    if (!response.ok) {
      throw new Error(typeof data?.error === 'string' ? data.error : `Request failed: ${response.status}`)
    }
    const attachmentPayload = data as AttachmentExtractionResponse
    const preparedAttachment = pendingAttachmentFromPayload(attachmentPayload)
    const draftDepartment = draftAttachmentDepartment.value
    const autoGenerateDocuments = draftAttachmentAutoGenerateDocuments.value
    draftAttachmentDepartment.value = null
    draftAttachmentAutoGenerateDocuments.value = false
    if (draftDepartment) {
      await startIcSubstrateNewChat(draftDepartment, 'improve_draft', preparedAttachment, autoGenerateDocuments)
      return
    }
    pendingAttachment.value = preparedAttachment
    await nextTick()
    autoResizeTextarea()
    textareaRef.value?.focus()
  } catch (error) {
    draftAttachmentDepartment.value = null
    draftAttachmentAutoGenerateDocuments.value = false
    globalError.value = formatError(error, t.value.attachmentUploadError)
  } finally {
    uploadingAttachment.value = false
  }
}

