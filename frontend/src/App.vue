    }
  }
  if (!canOpenGoCoding.value && sessionId.value) {
    await syncCurrentSessionDetail(sessionId.value)
    await nextTick()
  }
  if (canOpenGoCoding.value) {
    await openGoCoding()
    return true
  }
  globalError.value = goCodingNotReadyMessage()
  return false
}

